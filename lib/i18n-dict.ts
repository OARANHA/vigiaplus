export const DICT: Record<Locale, Record<string, string>> = { en: {}, it: IT, pt: PT };

/** Versione sincrona per i componenti client, che ricevono già il locale. */
export function tFor(locale: Locale) {
  const dict = DICT[locale];
  return (key: string, fallback: string) => dict[key] ?? fallback;
}

/**
 * Sostituisce i segnaposto {x} in una stringa del dizionario. Utile per le
 * chiavi con numeri dentro ("{n} sezioni selezionate"): la funzione t()
 * restituisce la stringa grezza, qui si compongono i valori.
 */
export function fmt(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in values ? String(values[k]) : m));
}

/**
 * Locale per i componenti client che non ricevono prop dal server (SearchBox,
 * TranslateBar, CopyButton…). Sul client legge l'attributo lang dell'<html>
 * (scritto dal layout); sul server usa il tag globale impostato dal layout,
 * così SSR e idratazione producono lo stesso testo.
 */
export function clientLocale(): Locale {
  const raw = typeof document !== 'undefined'
    ? document.documentElement.lang
    : globalThis.__srLocaleTag;
  if (raw === 'pt' || raw === 'pt-BR') return 'pt';
  if (raw === 'it' || raw === 'it-IT') return 'it';
  return 'en';
}

declare global {
  var __srLocaleTag: string | undefined;
}

/** Formattazione date coerente con la lingua scelta. */
export function localeTag(locale: Locale): string {
  if (locale === 'it') return 'it-IT';
  if (locale === 'pt') return 'pt-BR';
  return 'en-US';
}
